export function presentationCopy(lang) {
  return lang === 'he' ? PRESENTATION_COPY.he : PRESENTATION_COPY.en;
}

export function uploadErrorMessage(lang, code) {
  const c = presentationCopy(lang).uploadErrors;
  const table = lang === 'he' ? PRESENTATION_ERRORS.he : PRESENTATION_ERRORS.en;
  return c[code] || table[code] || c.default;
}

