export function presentationErrorMessage(lang, code) {
  const table = lang === 'he' ? PRESENTATION_ERRORS.he : PRESENTATION_ERRORS.en;
  const upload = presentationCopy(lang).uploadErrors;
  const c = String(code || '');
  if (table[c]) return table[c];
  if (upload[c]) return upload[c];
  if (/^http_401$/.test(c)) return table.unauthorized;
  if (/^http_403$/.test(c)) return table.forbidden;
  if (/^http_404$/.test(c)) return table.quote_not_found;
  if (/^http_413$/.test(c)) return table.payload_too_large;
  if (/^http_5\d\d$/.test(c) || c === 'internal_error' || c === 'server_misconfigured') return table.database_unavailable;
  return table.default;
}
