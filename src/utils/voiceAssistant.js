// microphone and spoken answers - "שברירת המחדל תהיה בקול אבל שתהיה אפשרות למשתמש לבחור גם וגם".
//  - voice (default): the answer is read aloud and its bubble shows a short "spoken answer" line with "show text";
//  - both: read aloud AND the full text;  - text: no speech.
// The choice is a per-browser convenience (localStorage, fail-safe). The server (voice-ai) decides the language from the account.

export const VOICE_MODES = Object.freeze(['voice', 'both', 'text']);
export const DEFAULT_VOICE_MODE = 'voice';
export const MAX_RECORD_SECONDS = 60;
const MODE_KEY = 'tekango.voiceMode';
const DISCLOSED_KEY = 'tekango.voiceDisclosed';

export function readVoiceMode() {
  try {
    const v = window.localStorage.getItem(MODE_KEY);
    return VOICE_MODES.includes(v) ? v : DEFAULT_VOICE_MODE;
  } catch { return DEFAULT_VOICE_MODE; }
}
export function saveVoiceMode(mode) {
  if (!VOICE_MODES.includes(mode)) return;
  try { window.localStorage.setItem(MODE_KEY, mode); } catch { /* the choice still applies for this session */ }
}
export function readVoiceDisclosed() {
  try { return window.localStorage.getItem(DISCLOSED_KEY) === '1'; } catch { return false; }
}
export function saveVoiceDisclosed() {
  try { window.localStorage.setItem(DISCLOSED_KEY, '1'); } catch { /* shown again next time - harmless */ }
}

/** The recorder format this browser supports (Chrome / Firefox: webm-opus, Safari: mp4-aac); null = no voice recording here. */
export function pickRecorderMime(Recorder = typeof window !== 'undefined' ? window.MediaRecorder : undefined) {
  if (!Recorder || typeof Recorder.isTypeSupported !== 'function') return null;
  for (const t of ['audio/webm;codecs=opus', 'audio/webm', 'audio/mp4', 'audio/ogg;codecs=opus']) {
    if (Recorder.isTypeSupported(t)) return t;
  }
  return null;
}

export function voiceSupported(nav = typeof navigator !== 'undefined' ? navigator : undefined) {
  return !!(nav?.mediaDevices?.getUserMedia) && !!pickRecorderMime();
}

export function blobToBase64(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result || '').split(',')[1] || '');
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(blob);
  });
}

export function base64ToBlob(b64, type) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new Blob([bytes], { type });
}

/** The voice-ai transcription call for dictation (the AI smart quote): { ok, text } | { ok: false, code: 'limit' | 'failed' }. */
export async function transcribeRecording(client, blob) {
  try {
    const audio = await blobToBase64(blob);
    const { data, error } = await client.functions.invoke('voice-ai', { body: { mode: 'transcribe', audio, mime: blob.type } });
    // Owner 2026-10-20: 403 smart_pack_required = voice is SMART PACK (the plan system is enforced)
    if (error) return { ok: false, code: error?.context?.status === 429 ? 'limit' : error?.context?.status === 403 ? 'smart_pack' : 'failed' };
    return data?.ok ? { ok: true, text: String(data.text || '') } : { ok: false, code: 'failed' };
  } catch { return { ok: false, code: 'failed' }; }
}

